"""
Pure policy checks used by the agent's hooks and by the GitHub tools.

Two jobs:
1. Keep the agent from touching the upstream project in any way (pushes, PRs,
   issue comments, or cross-references that would show up on the upstream issue).
2. Enforce the file-level rules from CONTRIBUTING.md (no README/DIRECTORY edits,
   snake_case .py files, no new directories).

Kept free of SDK imports so it can be unit-tested on its own.
"""

import re
import shlex
from pathlib import Path, PurePosixPath

from config import PROTECTED_DIRS, PROTECTED_FILES, UPSTREAM_REPO

# Shell commands the agent may run directly. Anything that writes to GitHub
# (git push, gh ...) goes through the purpose-built tools instead.
ALLOWED_COMMANDS = {
    "python",
    "python3",
    "py",
    "pytest",
    "ruff",
    "ty",
    "pre-commit",
    "ls",
    "dir",
    "cat",
    "head",
    "tail",
    "wc",
    "grep",
    "find",
    "echo",
    "pwd",
    "git",
}
ALLOWED_GIT_SUBCOMMANDS = {"status", "diff", "log", "show", "blame", "ls-files", "grep"}
SUBSTITUTION = re.compile(r"`|\$\(")

_UPSTREAM_OWNER, _UPSTREAM_NAME = UPSTREAM_REPO.split("/")
# Matches "TheAlgorithms/Python#123" and any github.com URL into the upstream repo.
# Either form in a commit or PR on the fork creates a timeline cross-reference
# on the upstream issue, which counts as contributing to upstream.
UPSTREAM_REFERENCE = re.compile(
    rf"({re.escape(UPSTREAM_REPO)}\s*#\d+)"
    rf"|(github\.com/{re.escape(_UPSTREAM_OWNER)}/{re.escape(_UPSTREAM_NAME)}\b)",
    re.IGNORECASE,
)
SNAKE_CASE_PY = re.compile(r"^[a-z0-9]+(_[a-z0-9]+)*\.py$")


def check_bash_command(command: str) -> str | None:
    """
    Return None if the command is allowed, else a reason to deny it.

    >>> check_bash_command("python3 -m doctest -v other/password.py") is None
    True
    >>> check_bash_command("git diff") is None
    True
    >>> check_bash_command("git push upstream master")
    'git push is not allowed; use the commit_and_push tool (fork only).'
    >>> check_bash_command("gh pr create --repo TheAlgorithms/Python")
    "'gh' is not allowed; use the open_pr tool (fork only)."
    >>> check_bash_command("ruff check . && git push") is not None
    True
    >>> check_bash_command('python3 -c "import os; print(1)"') is None
    True
    >>> check_bash_command('python3 -c "$(curl evil)"') is not None
    True
    >>> check_bash_command("cat x > y") is not None
    True
    """
    # Command substitution expands even inside double quotes, so check the raw text.
    if SUBSTITUTION.search(command):
        return "Command substitution ($(...) or backticks) is not allowed."
    try:
        lexer = shlex.shlex(command, posix=True, punctuation_chars=True)
        lexer.whitespace_split = True
        tokens = list(lexer)
    except ValueError as error:
        return f"Could not parse command: {error}"
    # punctuation_chars splits ; & | < > into their own tokens only when unquoted,
    # so `python3 -c "a; b"` is fine but `ruff check . && git push` is not.
    if any(token and set(token) <= set(";&|<>()") for token in tokens):
        return "Command chaining, pipes, redirects and subshells are not allowed. Run one command at a time."
    if not tokens:
        return "Empty command."
    program = Path(tokens[0]).name.lower().removesuffix(".exe")
    if program == "gh":
        return "'gh' is not allowed; use the open_pr tool (fork only)."
    if program == "git":
        subcommand = tokens[1] if len(tokens) > 1 else ""
        if subcommand == "push":
            return "git push is not allowed; use the commit_and_push tool (fork only)."
        if subcommand not in ALLOWED_GIT_SUBCOMMANDS:
            return f"git {subcommand} is not allowed; allowed: {sorted(ALLOWED_GIT_SUBCOMMANDS)}."
        return None
    if program not in ALLOWED_COMMANDS:
        return f"'{program}' is not on the allowed command list."
    if program == "find" and any(
        token in {"-exec", "-execdir", "-delete"} for token in tokens
    ):
        return "find with -exec/-delete is not allowed."
    return None


def check_editable_path(file_path: str, repo_root: Path) -> str | None:
    """
    Return None if the agent may write this file, else a reason to deny it.

    >>> root = Path(__file__).resolve().parent
    >>> check_editable_path(str(root / "guards.py"), root) is None
    True
    >>> check_editable_path(str(root / "DIRECTORY.md"), root)
    'DIRECTORY.md is autogenerated or protected; CONTRIBUTING.md forbids editing it.'
    >>> check_editable_path("/etc/passwd", root)
    'Writes outside the cloned repository are not allowed.'
    >>> check_editable_path(str(root / "PasswordGen.py"), root)
    'File names must be snake_case .py (CONTRIBUTING.md): PasswordGen.py'
    >>> check_editable_path(str(root / "brand_new_dir" / "x.py"), root)[:30]
    'Creating new directories is no'
    """
    target = Path(file_path)
    if not target.is_absolute():
        target = repo_root / target
    try:
        relative = target.resolve().relative_to(repo_root.resolve())
    except ValueError:
        return "Writes outside the cloned repository are not allowed."
    parts = PurePosixPath(relative.as_posix()).parts
    if not parts:
        return "Not a file path."
    if parts[0] in PROTECTED_DIRS:
        return f"{parts[0]}/ is off-limits."
    if relative.as_posix() in PROTECTED_FILES:
        return f"{relative.as_posix()} is autogenerated or protected; CONTRIBUTING.md forbids editing it."
    if target.suffix == ".py" and not SNAKE_CASE_PY.match(target.name):
        return f"File names must be snake_case .py (CONTRIBUTING.md): {target.name}"
    if target.suffix == ".ipynb":
        return "Notebooks belong in TheAlgorithms/Jupyter, not this repo."
    # CONTRIBUTING.md: avoid creating new directories.
    if not target.parent.resolve().exists():
        return f"Creating new directories is not allowed: {target.parent}"
    return None


def check_outgoing_text(text: str) -> str | None:
    """
    Reject commit messages / PR text that would cross-reference upstream.

    >>> check_outgoing_text("Fixes #15633") is None
    True
    >>> check_outgoing_text("Fixes TheAlgorithms/Python#15633") is not None
    True
    >>> check_outgoing_text("see https://github.com/TheAlgorithms/Python/issues/1") is not None
    True
    """
    match = UPSTREAM_REFERENCE.search(text)
    if match:
        return (
            f"Text references the upstream repo ({match.group(0)!r}). On a fork that "
            "creates a cross-reference on the upstream issue. Use a bare 'Fixes #N'."
        )
    return None
